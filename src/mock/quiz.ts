// ---------- 生成服务（模拟） ----------
/** 题型优先级：客观题优先，简答题靠后（题量不足放宽补充时先补客观题） */
const PRIORITY_TYPES: QuizType[] = ['single', 'multi', 'indefinite', 'judge', 'blank']

export interface QuizFilter {
  courseId: string
  noteId: string // 'all' 表示该课程全部章节
  types: QuizType[]
  difficulty: QuizDifficulty | '全部'
  count: number
}

const cache = new Map<string, QuizQuestion[]>()

export function quizCacheKey(f: QuizFilter): string {
  return [f.courseId, f.noteId, f.types.join(','), f.difficulty, f.count].join('|')
}

export function getCachedQuiz(f: QuizFilter): QuizQuestion[] | undefined {
  return cache.get(quizCacheKey(f))
}

function shuffle<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    const a = arr[i]!
    const b = arr[j]!
    arr[i] = b
    arr[j] = a
  }
  return arr
}

/**
 * 按筛选条件从题库抽题，数量不足时逐级放宽：
 * 同课程同题型不限难度 → 同课程客观题 → 同课程不限题型 → 不限课程
 * 同条件命中缓存直接返回（fromCache），force = true 时重新抽题并覆盖缓存
 */
export function generateQuiz(f: QuizFilter, opts: { force?: boolean } = {}): { questions: QuizQuestion[]; fromCache: boolean } {
  const key = quizCacheKey(f)
  if (!opts.force) {
    const hit = cache.get(key)
    if (hit) return { questions: hit, fromCache: true }
  }

  const base = QUIZ_BANK.filter((t) => t.course === f.courseId && (f.noteId === 'all' || t.noteId === f.noteId))
  const pool = shuffle(base.filter((t) => f.types.includes(t.type) && (f.difficulty === '全部' || t.difficulty === f.difficulty)))
  const picked = pool.slice(0, f.count)

  if (picked.length < f.count) {
    // 同课程同题型、不限难度
    const got = new Set(picked)
    for (const t of shuffle(base.filter((t) => f.types.includes(t.type) && !got.has(t)))) {
      if (picked.length >= f.count) break
      got.add(t)
      picked.push(t)
    }
    // 同课程、客观题优先（选择题/判断题/填空题）
    for (const t of shuffle(base.filter((t) => PRIORITY_TYPES.includes(t.type) && !got.has(t)))) {
      if (picked.length >= f.count) break
      got.add(t)
      picked.push(t)
    }
    // 同课程不限题型
    for (const t of shuffle(base.filter((t) => !got.has(t)))) {
      if (picked.length >= f.count) break
      got.add(t)
      picked.push(t)
    }
    // 兜底：其他课程
    if (picked.length < f.count) {
      for (const t of shuffle(QUIZ_BANK.filter((t) => !got.has(t)))) {
        if (picked.length >= f.count) break
        picked.push(t)
      }
    }
  }

  const out = picked.slice(0, f.count)
  cache.set(key, out)
  return { questions: out, fromCache: false }
}
